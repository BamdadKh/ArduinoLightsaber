# Rows of HILT (0-based) that show the kyber crystal window (drawn animated in firmware).
HILT_CRYSTAL_ROW = 20

# Small 7x5 status glyphs: battery body and "no sound".
NOSOUND = """
..#...#
.##..#.
###.#..
###..#.
.##...#
"""


def parse(art):
    rows = [r for r in art.strip("\n").split("\n")]
    return [[1 if c == "#" else 0 for c in r] for r in rows]


def rows_to_bytes(px, width_bytes):
    out = []
    for r in px:
        v = 0
        for i, b in enumerate(r):
            if b:
                v |= 1 << (width_bytes * 8 - 1 - i)
        for k in range(width_bytes - 1, -1, -1):
            out.append((v >> (8 * k)) & 0xFF)
    return out


def font_rows():
    data = []
    for cols in FONT_COLS:
        for r in range(7):
            v = 0
            for c in range(5):
                if (cols[c] >> r) & 1:
                    v |= 1 << (4 - c)
            data.append(v)
    return data


def fmt(name, data, per_line=16):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + per_line]) + ",")
    return f"const uint8_t {name}[] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    parts = [
        "// Generated by firmware/tools/gen_assets.py - edit the art there, not here.\n",
        "#pragma once\n#include <stdint.h>\n#include \"platform.h\"\n\n",
        "#define FONT_FIRST 0x20\n#define FONT_LAST 0x5A\n#define FONT_H 7\n",
        fmt("FONT5X7", font_rows()),
        "\n// Menu icons, 16x16, 2 bytes per row\n",
    ]
    names = list(ICONS)
    for i, n in enumerate(names):
        px = parse(ICONS[n])
        assert len(px) == 16 and all(len(r) == 16 for r in px), n
        parts.append(f"#define ICON_{n} {i}\n")
    icon_bytes = []
    for n in names:
        icon_bytes += rows_to_bytes(parse(ICONS[n]), 2)
    parts.append(f"#define ICON_COUNT {len(names)}\n")
    parts.append(fmt("ICONS16", icon_bytes))

    hilt = parse(HILT)
    assert all(len(r) == 12 for r in hilt)
    parts.append(f"\n#define HILT_W 12\n#define HILT_H {len(hilt)}\n#define HILT_CRYSTAL_ROW {HILT_CRYSTAL_ROW}\n")
    parts.append(fmt("HILT_BMP", rows_to_bytes(hilt, 2)))

    ns = parse(NOSOUND)
    parts.append(f"\n#define NOSOUND_W 7\n#define NOSOUND_H {len(ns)}\n")
    parts.append(fmt("NOSOUND_BMP", rows_to_bytes(ns, 1)))

    OUT_H.write_text("".join(parts), newline="\n")
    print("wrote", OUT_H)

    try:
        from PIL import Image
    except ImportError:
        return
    OUT_PNG.parent.mkdir(exist_ok=True)
    s = 4
    img = Image.new("L", ((len(names) * 18) * s, 60 * s), 0)
    for i, n in enumerate(names):
        for y, r in enumerate(parse(ICONS[n])):
            for x, b in enumerate(r):
                if b:
                    img.paste(255, ((i * 18 + x) * s, y * s, (i * 18 + x + 1) * s, (y + 1) * s))
    fr = font_rows()
    for g in range(len(FONT_COLS)):
        for y in range(7):
            for x in range(5):
                if fr[g * 7 + y] & (1 << (4 - x)):
                    X, Y = (g % 40) * 6 + x, 20 + (g // 40) * 9 + y
                    img.paste(255, (X * s, Y * s, (X + 1) * s, (Y + 1) * s))
    for y, r in enumerate(hilt):
        for x, b in enumerate(r):
            if b:
                img.paste(255, ((250 + x) * s, (20 + y) * s, (251 + x) * s, (21 + y) * s))
    img.save(OUT_PNG)
    print("wrote", OUT_PNG)


if __name__ == "__main__":
    main()
